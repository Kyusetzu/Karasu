#!/usr/bin/env node
/**
 * Regenerates src/lib/htmlEntities.data.ts from the WHATWG entity table; only `;`-terminated names, as `ENTITY_RE` demands.
 *
 *   node scripts/gen-entities.mjs                 fetches https://html.spec.whatwg.org/entities.json
 *   node scripts/gen-entities.mjs entities.json   reads a downloaded copy
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const SOURCE = "https://html.spec.whatwg.org/entities.json";
const OUT = join(ROOT, "src/lib/htmlEntities.data.ts");

const [local] = process.argv.slice(2);
const table = local ? JSON.parse(readFileSync(local, "utf8")) : await (await fetch(SOURCE)).json();

const names = Object.keys(table)
  .filter((k) => k.startsWith("&") && k.endsWith(";"))
  .map((k) => k.slice(1, -1))
  .sort();

// Escape only what a literal needs, so the file shows glyphs; U+2028/2029 would be legal but invisible in a review.
const literal = (s) =>
  JSON.stringify(s).replaceAll("\u2028", "\\u2028").replaceAll("\u2029", "\\u2029");

const lines = names.map((n) => `  ${literal(n)}: ${literal(table[`&${n};`].characters)},`);
const header = `// Generated by scripts/gen-entities.mjs from ${SOURCE} — do not edit by hand.
// ${names.length} named character references: the \`;\`-terminated set, which is
// every name a browser decodes when the semicolon is present.

/** Every named entity a browser decodes, keyed by the name between \`&\` and \`;\`. */
export const HTML5_ENTITIES: Record<string, string> = {
`;
writeFileSync(OUT, `${header}${lines.join("\n")}\n};\n`);
console.log(`wrote ${OUT}: ${names.length} names`);
