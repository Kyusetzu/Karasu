#!/usr/bin/env node
/**
 * Turns the raw captures (`captures/desktop/*.png` at 4x from the rig,
 * `captures/phone/*.png` from adb) into what the page ships, and writes the
 * manifest the components read.
 *
 * Desktop: 2880 and 1440 wide (2x and 1x of the 1440x900 window). Phone:
 * 1216 and 608. AVIF at both widths; WebP and JPEG at the 1x width only, as
 * the fallbacks for browsers without AVIF (the `<img>` itself names the JPEG). Derivatives land under
 * `src/assets/screenshots/` so Vite hashes them; the raw PNGs stay ignored.
 *
 *   node scripts/process-screenshots.mjs           everything
 *   node scripts/process-screenshots.mjs --only id  one screenshot
 */
import { existsSync, mkdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import sharp from "sharp";
import { DESKTOP, PHONE } from "./shots.config.mjs";

const here = path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1"));
const SITE = path.resolve(here, "..");
const OUT = path.join(SITE, "src", "assets", "screenshots");
const MANIFEST = path.join(SITE, "src", "content", "screenshots.ts");

const only = process.argv.includes("--only") ? process.argv[process.argv.indexOf("--only") + 1] : null;

const SETS = [
  { kind: "desktop", dir: path.join(SITE, "captures", "desktop"), shots: DESKTOP, widths: [2880, 1440], fallback: 1440 },
  { kind: "phone", dir: path.join(SITE, "captures", "phone"), shots: PHONE, widths: [1216, 608], fallback: 608 },
];

mkdirSync(OUT, { recursive: true });
const entries = [];
const imports = [];
let n = 0;

for (const set of SETS) {
  mkdirSync(path.join(OUT, set.kind), { recursive: true });
  for (const shot of set.shots) {
    if (only && shot.id !== only) continue;
    const src = path.join(set.dir, shot.file);
    if (!existsSync(src)) {
      console.warn(`process: missing capture ${path.relative(SITE, src)} — skipped`);
      continue;
    }
    const meta = await sharp(src).metadata();
    const ratio = meta.height / meta.width;
    const variants = { avif: [], webp: [], jpg: [] };
    for (const w of set.widths) {
      const h = Math.round(w * ratio);
      const base = sharp(src).resize(w, h, { kernel: "lanczos3" });
      const avif = path.join(OUT, set.kind, `${shot.id}-${w}.avif`);
      const webp = path.join(OUT, set.kind, `${shot.id}-${w}.webp`);
      // The 2x file is viewed at half its pixels, so it can afford a lower quality.
      await base.clone().avif({ quality: w >= 2000 ? 45 : 52, effort: 6 }).toFile(avif);
      variants.avif.push([w, avif]);
      // WebP only at the fallback width: every current browser takes the AVIF,
      // and a 2x WebP of a cover grid is 400 kB nobody would download.
      if (w === set.fallback) {
        await base.clone().webp({ quality: 80, effort: 5 }).toFile(webp);
        variants.webp.push([w, webp]);
      }
      if (w === set.fallback) {
        const jpg = path.join(OUT, set.kind, `${shot.id}-${w}.jpg`);
        await base.clone().jpeg({ quality: 82, mozjpeg: true }).toFile(jpg);
        variants.jpg.push([w, jpg]);
      }
      console.log(`process: ${shot.id} @${w}  avif ${(statSync(avif).size / 1024).toFixed(0)} kB`);
    }
    const width = set.widths[0];
    const height = Math.round(width * ratio);
    const varName = (fmt, w) => `s${n}_${fmt}_${w}`;
    for (const fmt of ["avif", "webp", "jpg"]) {
      for (const [w, file] of variants[fmt]) {
        imports.push(`import ${varName(fmt, w)} from "@/assets/screenshots/${set.kind}/${path.basename(file)}";`);
      }
    }
    const list = (fmt) => `[${variants[fmt].map(([w]) => `{ w: ${w}, src: ${varName(fmt, w)} }`).join(", ")}]`;
    entries.push(
      `  {\n    id: ${JSON.stringify(shot.id)},\n    kind: ${JSON.stringify(set.kind)},\n    width: ${width},\n    height: ${height},\n    alt: ${JSON.stringify(shot.alt)},\n    caption: ${JSON.stringify(shot.caption)},\n    avif: ${list("avif")},\n    webp: ${list("webp")},\n    jpg: ${list("jpg")},\n  }`,
    );
    n++;
  }
}

if (only) {
  console.log("process: --only does not rewrite the manifest; run without it once");
  process.exit(0);
}

// Stale derivatives from a renamed shot would otherwise linger in the tree.
for (const set of SETS) {
  const keep = new Set(set.shots.map((s) => s.id));
  const dir = path.join(OUT, set.kind);
  for (const f of (await import("node:fs")).readdirSync(dir)) {
    const id = f.replace(/-\d+\.(avif|webp|jpg)$/, "");
    if (!keep.has(id)) rmSync(path.join(dir, f));
  }
}

const ts = `// GENERATED by scripts/process-screenshots.mjs from scripts/shots.config.mjs — do not edit.
${imports.join("\n")}

export interface Source {
  w: number;
  src: string;
}

export interface Shot {
  id: string;
  kind: "desktop" | "phone";
  /** Intrinsic size of the largest variant; the <img> carries it so nothing shifts. */
  width: number;
  height: number;
  /** One present-tense sentence naming the screen and what is on it. */
  alt: string;
  caption: string;
  avif: Source[];
  webp: Source[];
  /** The fallback the <img> itself names, at 1x. */
  jpg: Source[];
}

export const SHOTS: Shot[] = [
${entries.join(",\n")},
];

export const shot = (id: string): Shot => {
  const s = SHOTS.find((x) => x.id === id);
  if (!s) throw new Error(\`no screenshot \${id}\`);
  return s;
};
`;
writeFileSync(MANIFEST, ts);
console.log(`process: ${entries.length} screenshots, manifest written`);
